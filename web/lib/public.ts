// ---------- Fetch helpers (server only; cached with ISR under the "public" tag) ----------

export async function getBooks(filters: { age?: number; theme?: string } = {}) {
  const qs = new URLSearchParams();
  if (filters.age !== undefined) qs.set("age", String(filters.age));
  if (filters.theme) qs.set("theme", filters.theme);
  const query = qs.size ? `?${qs}` : "";
  const data = await publicApi<{ books: PublicBook[] }>(`/api/public/books${query}`);
  return data?.books ?? null;
}

export const getBook = (slug: string) => publicApi<BookDetail>(`/api/public/books/${encodeURIComponent(slug)}`);

export const getFilters = () => publicApi<Filters>("/api/public/filters");

export async function getPosts(limit = 50) {
  const data = await publicApi<{ posts: PostSummary[] }>(`/api/public/posts?limit=${limit}`);
  return data?.posts ?? null;
}

export const getPost = (slug: string) => publicApi<Post>(`/api/public/posts/${encodeURIComponent(slug)}`);

