// ---------- Small formatting helpers ----------

export const SITE_NAME = "Crayonlark";
export const SITE_TAGLINE = "Little books for big imaginations";
export const SITE_URL = (process.env.PUBLIC_SITE_URL || process.env.NEXT_PUBLIC_SITE_URL || "http://localhost:3000").replace(
  /\/+$/,
  "",
);

export const absoluteUrl = (path: string) => (path.startsWith("http") ? path : `${SITE_URL}${path}`);

/** Same rule as python `core/pipeline.slugify`, so theme links match the API's theme slugs. */
export const slugify = (text: string) => text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

export const ageLabel = (b: Pick<PublicBook, "age_min" | "age_max">) =>
  b.age_min === b.age_max ? `Age ${b.age_min}` : `Ages ${b.age_min}–${b.age_max}`;

export const trimLabel = (trim: string) => (trim === "8.5x8.5" ? '8.5 × 8.5 in (square)' : '8.5 × 11 in (letter)');

export const formatDate = (iso: string) =>
  new Intl.DateTimeFormat("en-US", { dateStyle: "long", timeZone: "UTC" }).format(new Date(iso));

/** Plain-text summary from safe HTML, for meta descriptions. */
export function plainText(html: string, max = 160) {
  const text = html.replace(/<[^>]*>/g, " ").replace(/&nbsp;/g, " ").replace(/\s+/g, " ").trim();
  return text.length > max ? `${text.slice(0, max - 1).trimEnd()}…` : text;
}

// ---------- SEO ----------

/** Generated by app/og.png/route.tsx. */
const DEFAULT_OG_IMAGE = { url: "/og.png", width: 1200, height: 630, alt: `${SITE_NAME}: ${SITE_TAGLINE}` };

/** Per-page metadata: title, description, canonical URL, Open Graph and Twitter card. */
export function pageMetadata(opts: {
  title: string;
  description: string;
  path: string;
  image?: string | null;
  type?: "website" | "article";
  absoluteTitle?: boolean;
}): Metadata {
  const fullTitle = opts.absoluteTitle ? opts.title : `${opts.title} · ${SITE_NAME}`;
  const images = opts.image ? [{ url: opts.image, alt: opts.title }] : [DEFAULT_OG_IMAGE];
  return {
    title: opts.absoluteTitle ? { absolute: opts.title } : opts.title,
    description: opts.description,
    alternates: { canonical: opts.path },
    openGraph: {
      title: fullTitle,
      description: opts.description,
      url: opts.path,
      siteName: SITE_NAME,
      locale: "en_US",
      type: opts.type ?? "website",
      images,
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description: opts.description,
      images,
    },
  };
}

